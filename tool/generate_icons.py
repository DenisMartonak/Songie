#!/usr/bin/env python3
"""Draws the Songies icon (a sound wave that bends into an "S") and writes
every platform's icon files from it. Needs ImageMagick 7 (`magick`) built
with librsvg.

    python3 tool/generate_icons.py

Writes:
  assets/icon/songies_icon.svg             the full icon (source of truth)
  assets/icon/songies_icon_foreground.svg  the S alone, for Android's adaptive icon
  android/.../mipmap-*/ic_launcher.png     legacy launcher icons
  android/.../mipmap-*/ic_launcher_foreground.png
  android/.../mipmap-anydpi-v26/ic_launcher.xml
  android/.../drawable/ic_launcher_background.xml
  android/.../drawable/ic_stat_songies.xml notification icon (the S, white)
  windows/runner/resources/app_icon.ico
  linux/packaging/songies.png              512 px, for the AppImage
"""

import math
import os
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")

# Gradient behind the S: violet to pink, top left to bottom right.
GRADIENT_START = "#7C3AED"
GRADIENT_END = "#EC4899"

STROKE = 78  # stroke width in the 1024 px design
RX, RY = 178, 148  # half-width and half-height of the S's two bowls
TAIL = 300  # length of each wave tail, from the middle of the S
AMPLITUDE = 64  # peak height of the wave tails
WAVES = 1.5  # waves along each tail (a multiple of 0.5 keeps the join smooth)


def _half():
    """The upper half of the S, from the tip of the top wave tail to the
    centre (512, 512): the tail runs left along the top of the upper bowl,
    then the bowl curves round anticlockwise to the centre."""
    top = 512 - 2 * RY
    pts = []
    n = 48
    for i in range(n + 1):
        s = i / n  # 0 at the tip, 1 where the tail meets the bowl
        x = 512 + TAIL * (1 - s)
        # Zero height and zero slope at both ends, so the tail grows out of
        # a still line and joins the bowl smoothly.
        y = top - AMPLITUDE * math.sin(math.pi * s) * math.sin(2 * math.pi * WAVES * s)
        pts.append((x, y))
    cx, cy = 512, 512 - RY
    m = 40
    for i in range(1, m + 1):
        a = -math.pi / 2 - math.pi * i / m  # top, round the left, to the bottom
        pts.append((cx + RX * math.cos(a), cy + RY * math.sin(a)))
    return pts


def s_points():
    half = _half()
    # The lower half is the upper one turned half a circle about the centre.
    lower = [(1024 - x, 1024 - y) for (x, y) in reversed(half)]
    return half + lower[1:]


def path_data(pts, scale=1.0, offset=(0.0, 0.0), digits=1):
    """A smooth path through [pts] (Catmull-Rom as cubic Béziers)."""
    p = [(x * scale + offset[0], y * scale + offset[1]) for (x, y) in pts]
    f = lambda v: f"{v:.{digits}f}".rstrip("0").rstrip(".")
    out = [f"M{f(p[0][0])},{f(p[0][1])}"]
    for i in range(len(p) - 1):
        p0 = p[i - 1] if i > 0 else p[i]
        p1, p2 = p[i], p[i + 1]
        p3 = p[i + 2] if i + 2 < len(p) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        out.append(
            f"C{f(c1[0])},{f(c1[1])} {f(c2[0])},{f(c2[1])} {f(p2[0])},{f(p2[1])}"
        )
    return " ".join(out)


def icon_svg():
    d = path_data(s_points())
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{GRADIENT_START}"/>
      <stop offset="1" stop-color="{GRADIENT_END}"/>
    </linearGradient>
    <filter id="shadow" x="-20%" y="-20%" width="140%" height="140%">
      <feDropShadow dx="0" dy="14" stdDeviation="18" flood-color="#2E0A4F" flood-opacity="0.35"/>
    </filter>
  </defs>
  <rect width="1024" height="1024" rx="232" fill="url(#bg)"/>
  <path d="{d}" fill="none" stroke="#FFFFFF" stroke-width="{STROKE}"
        stroke-linecap="round" stroke-linejoin="round" filter="url(#shadow)"/>
</svg>
"""


# Android's adaptive icon shows the middle 66 of its 108 units; the S is
# shrunk to fit well inside that circle.
FOREGROUND_SCALE = 0.66


def foreground_svg():
    k = FOREGROUND_SCALE
    d = path_data(s_points(), scale=k, offset=(512 * (1 - k), 512 * (1 - k)))
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">
  <path d="{d}" fill="none" stroke="#FFFFFF" stroke-width="{STROKE * k:.1f}"
        stroke-linecap="round" stroke-linejoin="round"/>
</svg>
"""


def notification_vector():
    # 24 dp, white; the S fills about 20 dp.
    k = 20 / 760
    off = 12 - 512 * k
    d = path_data(s_points()[::2], scale=k, offset=(off, off), digits=2)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:pathData="{d}"
        android:strokeColor="#FFFFFFFF"
        android:strokeWidth="{STROKE * k * 1.15:.2f}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round" />
</vector>
"""


ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

BACKGROUND_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/generate_icons.py. -->
<shape xmlns:android="http://schemas.android.com/apk/res/android">
    <gradient
        android:angle="315"
        android:startColor="{GRADIENT_START}"
        android:endColor="{GRADIENT_END}" />
</shape>
"""

DENSITIES = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def render(svg, size, out):
    os.makedirs(os.path.dirname(out), exist_ok=True)
    subprocess.run(
        ["magick", "-background", "none", "-density", "384", svg,
         "-resize", f"{size}x{size}", "-strip", f"PNG32:{out}"],
        check=True,
    )


def main():
    icon = os.path.join(ROOT, "assets", "icon", "songies_icon.svg")
    fg = os.path.join(ROOT, "assets", "icon", "songies_icon_foreground.svg")
    write(icon, icon_svg())
    write(fg, foreground_svg())

    for name, k in DENSITIES.items():
        render(icon, round(48 * k), os.path.join(RES, f"mipmap-{name}", "ic_launcher.png"))
        render(fg, round(108 * k), os.path.join(RES, f"mipmap-{name}", "ic_launcher_foreground.png"))
    write(os.path.join(RES, "mipmap-anydpi-v26", "ic_launcher.xml"), ADAPTIVE_XML)
    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), BACKGROUND_XML)
    write(os.path.join(RES, "drawable", "ic_stat_songies.xml"), notification_vector())

    render(icon, 512, os.path.join(ROOT, "linux", "packaging", "songies.png"))

    with tempfile.TemporaryDirectory() as tmp:
        sizes = [16, 24, 32, 48, 64, 128, 256]
        pngs = []
        for s in sizes:
            p = os.path.join(tmp, f"{s}.png")
            render(icon, s, p)
            pngs.append(p)
        subprocess.run(
            ["magick", *pngs, os.path.join(ROOT, "windows", "runner", "resources", "app_icon.ico")],
            check=True,
        )


if __name__ == "__main__":
    main()
